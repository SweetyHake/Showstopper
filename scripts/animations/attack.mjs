// --- Integration with Token-Displayed Weapons & Shields (Dynamic Items) ---
function triggerDynamicItemAttack(token1, token2, item, attackState, ctx) {
    const api = globalThis.showstopper?.dynamicItems?.manager ?? globalThis.showstopper?.itemDisplay;
    if (!api || typeof api.animateItemAttack !== "function")
        return;
    let attackerItemId = null;
    if (item?.id) {
        const direct = api.getDisplay?.(token1.id, item.id);
        if (direct?.config?.enabled)
            attackerItemId = item.id;
    }
    if (!attackerItemId && (ctx.delivery === "mwak" || ctx.delivery === "rwak")) {
        const all = api.getAllDisplays?.(token1.id) ?? [];
        for (const entry of all) {
            if (!entry?.config?.enabled)
                continue;
            const actorItem = token1.actor?.items?.get?.(entry.itemId);
            if (actorItem?.type === "weapon" && actorItem?.system?.type?.value !== "shield") {
                attackerItemId = entry.itemId;
                break;
            }
        }
    }
    if (!attackerItemId)
        return;
    let targetItemId = null;
    let defenderHasWeapon = false;
    let defenderHasShield = false;
    if (attackState === "blocked") {
        const defDisplays = api.getAllDisplays?.(token2.id) ?? [];
        for (const entry of defDisplays) {
            if (!entry?.config?.enabled)
                continue;
            const defItem = token2.actor?.items?.get?.(entry.itemId);
            if (defItem?.system?.type?.value === "shield") {
                targetItemId = entry.itemId;
                defenderHasShield = true;
                break;
            }
            if (!targetItemId && defItem?.type === "weapon") {
                targetItemId = entry.itemId;
                defenderHasWeapon = true;
            }
        }
    }
    let style = "swing";
    if (ctx.delivery === "rwak" || ctx.delivery === "rsak") {
        style = "ranged";
    }
    else if (attackState === "blocked") {
        style = defenderHasWeapon && !defenderHasShield ? "parry" : "block";
    }
    else if (attackState === "miss") {
        style = "miss";
    }
    else if (ctx.damageType === "piercing") {
        style = "pierce";
    }
    void api.animateItemAttack(token1.id, attackerItemId, [token2.id], style, {
        withBodyLunge: ctx.delivery === "mwak" || ctx.delivery === "msak",
        suppressShake: true,
        targetItemId
    });
}
