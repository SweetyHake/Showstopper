// Combo chain tracker (Extra Attack / Multiattack / Scorching Ray / Eldritch Blast)
const comboStateByToken = new Map();
function enqueueTokenJob(tokenId, job) {
    pendingTokenJobs.set(tokenId, (pendingTokenJobs.get(tokenId) ?? 0) + 1);
    const prev = attackQueues.get(tokenId) ?? Promise.resolve();
    const task = prev.catch(() => { }).then(job);
    attackQueues.set(tokenId, task);
    task.catch(() => { }).finally(() => {
        const nextCount = Math.max(0, (pendingTokenJobs.get(tokenId) ?? 1) - 1);
        if (nextCount === 0)
            pendingTokenJobs.delete(tokenId);
        else
            pendingTokenJobs.set(tokenId, nextCount);
        if (attackQueues.get(tokenId) === task)
            attackQueues.delete(tokenId);
    });
    return task;
}
function nextComboState(tokenId) {
    const now = performance.now();
    const prev = comboStateByToken.get(tokenId);
    if (prev && (now - prev.lastEndAt) <= CFG.COMBO_WINDOW_MS) {
        prev.count += 1;
        prev.side = -prev.side;
        prev.lastEndAt = now;
        return { comboIndex: prev.count, comboSide: prev.side };
    }
    const initialSide = Math.random() < 0.5 ? 1 : -1;
    const fresh = { count: 0, lastEndAt: now, side: initialSide };
    comboStateByToken.set(tokenId, fresh);
    return { comboIndex: 0, comboSide: initialSide };
}
function touchComboEnd(tokenId) {
    const st = comboStateByToken.get(tokenId);
    if (st)
        st.lastEndAt = performance.now();
}
