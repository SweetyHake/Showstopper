function hasShieldEquipped(actor) {
    return !!actor?.shield
        || (actor?.items ?? []).some(item => item.system?.equipped && item.system?.type?.value === "shield");
}
export function determineAttackState(total, AC, isCritical, isRanged, targetToken, isFumble = false) {
    if (isCritical)
        return "crit";
    if (isFumble)
        return isRanged ? "miss" : determineMissState(total, AC, targetToken);
    if (total >= AC)
        return "hit";
    if (AC - total < 5 && hasShieldEquipped(targetToken?.actor))
        return "blocked";
    return "miss";
}
export function determineMissState(total, AC, targetToken) {
    if (AC - total < 5 && hasShieldEquipped(targetToken?.actor))
        return "blocked";
    return "miss";
}
