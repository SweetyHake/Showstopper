/**
 * Cinematic combat attack animations (D&D 5e).
 *
 * Triggers:
 *  - `dnd5e.postRollAttack` (this file) — baseline path; attack outcome
 *    (`hit` / `miss` / `blocked` / `crit`) is inferred heuristically from roll total, d20, and target AC.
 *  - `midi-qol.AttackRollComplete` (`scripts/animations/attack-triggers.mjs`) —
 *    authoritative `hit` / `miss` / `crit` from the Midi-QOL workflow. While the Midi trigger is active
 *    (`sAnimSettings.midiTrigger`, enabled by default), the `dnd5e` hook stays silent
 *    to avoid playing animations twice.
 *
 * Supported attack delivery categories (`delivery`):
 *  - `"mwak"` — melee weapon and unarmed attacks (weapon profiles + Dynamic Items)
 *  - `"rwak"` — ranged weapon attacks (shooter recoil, arrow/bolt flight, target reaction)
 *  - `"msak"` — melee spell attacks (cast flash, lunge, elemental burst)
 *  - `"rsak"` — ranged spell attacks (cast aura, elemental bolt, impact/dodge)
 *
 * Visual effects are played through Sequencer using the module's built-in
 * procedural VP9-alpha (`.webm`) assets (`assets/attacks/*.webm`) with no JB2A dependency.
 */
