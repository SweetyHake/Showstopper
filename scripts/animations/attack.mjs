function syncDarkenOverlayVisibility() {
    const el = document.getElementById("sweety-darken-overlay");
    if (!el)
        return;
    el.classList.toggle("active", _activeDarkenTimers.size > 0);
}
function clearDarkenEffectLocal(name = null) {
    if (name) {
        const timer = _activeDarkenTimers.get(name);
        if (timer)
            clearTimeout(timer);
        _activeDarkenTimers.delete(name);
    }
    else {
        for (const timer of _activeDarkenTimers.values())
            clearTimeout(timer);
        _activeDarkenTimers.clear();
    }
    syncDarkenOverlayVisibility();
}
function darkenSceneLocal({ name, duration = 4000 } = {}) {
    if (!name)
        return;
    ensureDarkenOverlay();
    const prev = _activeDarkenTimers.get(name);
    if (prev)
        clearTimeout(prev);
    const timeoutMs = Math.min(DARKEN_SAFETY_TIMEOUT, Math.max(2000, Number(duration || 0) + 1500));
    const timer = setTimeout(() => clearDarkenEffectLocal(name), timeoutMs);
    _activeDarkenTimers.set(name, timer);
    syncDarkenOverlayVisibility();
}
